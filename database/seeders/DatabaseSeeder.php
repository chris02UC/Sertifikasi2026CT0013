<?php

namespace Database\Seeders;

use App\Enums\GarageType;
use App\Enums\RentalType;
use App\Enums\VehicleType;
use App\Models\Garage;
use App\Models\Rental;
use App\Models\RentalExtension;
use App\Models\User;
use App\Models\Vehicle;
use App\Services\GarageService;
use App\Services\PricingService;
use App\Services\RentalPeriodService;
use Carbon\Carbon;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Storage;

/**
 * Demo data. Every password is "password".
 *
 * Accounts: admin1 (admin); renter1-renter2 approved, renter3-renter4 pending
 * (waiting for admin verification), renter5 rejected.
 * Garages of each type, vehicles for renter1/renter2, and rental history across several months.
 */
class DatabaseSeeder extends Seeder
{
    private const PROOF = 'payment-proofs/contoh-bukti-transfer.png';

    public function run(GarageService $garages, PricingService $pricing, RentalPeriodService $period): void
    {
        $this->createSampleProof();

        $admin = User::factory()->admin()->create([
            'nik' => '3578010101900001', 'name' => 'admin1', 'phone' => '081200000001', 'email' => 'admin1@sewagarasi.test',
        ]);

        $renter1 = User::factory()->create(['nik' => '3578010202950002', 'name' => 'renter1', 'phone' => '081200000002', 'email' => 'renter1@sewagarasi.test']);
        $renter2 = User::factory()->create(['nik' => '3578010303960003', 'name' => 'renter2', 'phone' => '081200000003', 'email' => 'renter2@sewagarasi.test']);
        User::factory()->pending()->create(['nik' => '3578010404970004', 'name' => 'renter3', 'phone' => '081200000004', 'email' => 'renter3@sewagarasi.test']);
        User::factory()->pending()->create(['nik' => '3578010505980005', 'name' => 'renter4', 'phone' => '081200000005', 'email' => 'renter4@sewagarasi.test']);
        User::factory()->rejected()->create(['nik' => '3578010606990006', 'name' => 'renter5', 'phone' => '081200000006', 'email' => 'renter5@sewagarasi.test', 'verified_at' => now()]);

        // Garages: S001-S010, C001-C010, E001-E005 (codes generated by GarageService).
        $garages->createBatch(GarageType::BICYCLE, 10, 5000, null);
        $garages->createBatch(GarageType::CAR, 10, 25000, null);
        $garages->createBatch(GarageType::ELECTRIC, 5, 40000, 2500);

        $motor = Vehicle::create(['user_id' => $renter1->id, 'type' => VehicleType::MOTORCYCLE, 'plate_number' => 'L 1234 AB', 'brand_model' => 'Honda Beat']);
        $ev = Vehicle::create(['user_id' => $renter1->id, 'type' => VehicleType::ELECTRIC_CAR, 'plate_number' => 'L 77 EV', 'brand_model' => 'Hyundai Ioniq 5', 'battery_kwh' => 72.6]);
        $avanza = Vehicle::create(['user_id' => $renter2->id, 'type' => VehicleType::CAR, 'plate_number' => 'L 5678 CD', 'brand_model' => 'Toyota Avanza']);
        $bicycle = Vehicle::create(['user_id' => $renter2->id, 'type' => VehicleType::BICYCLE, 'brand_model' => 'Polygon Heist']);

        $today = today();
        $rent = fn (Vehicle $v, string $code, RentalType $type, Carbon $start, ?int $days = null) => $this->rent($pricing, $period, $v, Garage::where('code', $code)->firstOrFail(), $type, $start, $days);

        // Finished rentals (history for the reports).
        $rent($motor, 'S001', RentalType::DAILY, Carbon::create($today->year, 1, 10), 5);
        $rent($avanza, 'C001', RentalType::MONTHLY, Carbon::create($today->year, 3, 1));
        $rent($ev, 'E001', RentalType::DAILY, Carbon::create($today->year, 6, 15), 7);
        $rent($bicycle, 'S002', RentalType::DAILY, Carbon::create($today->year, 6, 20), 3);
        $rent($ev, 'C002', RentalType::DAILY, Carbon::create($today->year, 9, 5), 2);

        // Rentals running today (can be extended by the admin).
        $active = $rent($avanza, 'C003', RentalType::DAILY, $today->copy()->subDays(3), 10);
        $rent($motor, 'S003', RentalType::MONTHLY, $today->copy()->subDays(5));
        $rent($ev, 'E002', RentalType::DAILY, $today->copy(), 4);

        // One sample extension by the admin: C003 extended by 5 days.
        $newEnd = $active->end_date->copy()->addDays(5);
        RentalExtension::create([
            'rental_id' => $active->id, 'admin_id' => $admin->id, 'old_end_date' => $active->end_date, 'new_end_date' => $newEnd,
            'added_days' => 5, 'amount_due' => $pricing->extensionCost($active->daily_price, $active->end_date, $newEnd),
            'payment_proof_path' => self::PROOF,
        ]);
        $active->update(['end_date' => $newEnd, 'duration_days' => $active->duration_days + 5]);

        $garages->syncStatuses($today);
    }

    /** Creates a rental directly (past dates are allowed for demo data only). */
    private function rent(PricingService $pricing, RentalPeriodService $period, Vehicle $vehicle, Garage $garage,
        RentalType $type, Carbon $start, ?int $days): Rental
    {
        $duration = $period->durationDays($type, $start, $days);
        $rentCost = $pricing->rentCost($type, $garage->daily_price, $duration);
        $chargingCost = $pricing->chargingCost($vehicle, $garage);

        return Rental::create([
            'vehicle_id' => $vehicle->id, 'garage_id' => $garage->id, 'rental_type' => $type,
            'start_date' => $start, 'end_date' => $period->endDate($start, $duration), 'duration_days' => $duration,
            'daily_price' => $garage->daily_price, 'rent_cost' => $rentCost, 'charging_cost' => $chargingCost,
            'total_cost' => $pricing->newRentalTotal($rentCost, $chargingCost), 'payment_proof_path' => self::PROOF,
        ]);
    }

    /** Sample transfer-proof image (drawn with GD) so the proof "Lihat" link can be opened. */
    private function createSampleProof(): void
    {
        $img = imagecreatetruecolor(480, 240);
        imagefill($img, 0, 0, imagecolorallocate($img, 240, 253, 250));
        $teal = imagecolorallocate($img, 15, 118, 110);
        imagerectangle($img, 8, 8, 471, 231, $teal);
        imagestring($img, 5, 140, 90, 'BUKTI TRANSFER', $teal);
        imagestring($img, 3, 150, 120, '(contoh data demo)', $teal);

        ob_start();
        imagepng($img);
        Storage::disk('public')->put(self::PROOF, ob_get_clean());
        imagedestroy($img);
    }
}
